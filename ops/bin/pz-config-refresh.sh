#!/usr/bin/env bash
# Render /etc/pz/env from SSM Parameter Store.
#
# This runs on EVERY boot (pz-config.service), which is the answer to DESIGN C6: because
# the instance is stopped and started rather than replaced, cloud-init never runs again,
# so anything frozen into user_data at first boot would be frozen forever. Config lives
# in Parameter Store instead, and this pulls it fresh each time. Change `game_xmx` in
# prod.tfvars, apply, and the next /pz start picks it up.
set -euo pipefail

ENV_FILE=/etc/pz/env
IMDS=http://169.254.169.254

log() { echo "pz-config: $*" >&2; }

token="$(curl -fsS -X PUT "$IMDS/latest/api/token" \
  -H "X-aws-ec2-metadata-token-ttl-seconds: 300")"
imds() { curl -fsS -H "X-aws-ec2-metadata-token: $token" "$IMDS/latest/$1"; }

REGION="$(imds meta-data/placement/region)"
INSTANCE_ID="$(imds meta-data/instance-id)"
export AWS_DEFAULT_REGION="$REGION"

# Which stack am I? From the instance's own tag, so nothing needs to be baked in.
# Instance metadata tags first (no API call); DescribeTags as the fallback.
STACK="$(imds meta-data/tags/instance/pz:stack 2>/dev/null || true)"
if [[ -z "$STACK" ]]; then
  log "IMDS tags unavailable, falling back to DescribeTags"
  STACK="$(aws ec2 describe-tags \
    --filters "Name=resource-id,Values=$INSTANCE_ID" "Name=key,Values=pz:stack" \
    --query 'Tags[0].Value' --output text)"
fi
if [[ -z "$STACK" || "$STACK" == "None" ]]; then
  log "FATAL: cannot determine pz:stack tag; refusing to guess"
  exit 1
fi

PREFIX="/pz/${STACK}"

# One call for the whole config tree. --with-decryption covers the SecureStrings
# (rcon_password, admin_password) that live alongside it.
params_json="$(aws ssm get-parameters-by-path \
  --path "$PREFIX" --recursive --with-decryption \
  --query 'Parameters[].{n:Name,v:Value}' --output json)"

get() {
  python3 -c '
import json,sys
want=sys.argv[1]
for p in json.load(sys.stdin):
    if p["n"].rsplit("/",1)[-1]==want or p["n"]==want:
        print(p["v"]); break
' "$1" <<<"$params_json"
}

SERVER_NAME="$(get server_name)"
XMX="$(get xmx)"
RCON_PASSWORD="$(get rcon_password)"
ADMIN_PASSWORD="$(get admin_password)"

for required in SERVER_NAME XMX RCON_PASSWORD; do
  if [[ -z "${!required}" ]]; then
    log "FATAL: $required missing under $PREFIX -- see DEPLOY.md 'Secrets'"
    exit 1
  fi
done

umask 077
install -d -m 0755 /etc/pz
tmp="$(mktemp)"
cat >"$tmp" <<ENVEOF
# Generated by pz-config-refresh.sh on $(date -Is). Do not edit by hand -- every boot
# overwrites this file. Change the values in SSM Parameter Store (or prod.tfvars for
# the non-secret ones) instead.
PZ_STACK=${STACK}
PZ_REGION=${REGION}
PZ_INSTANCE_ID=${INSTANCE_ID}
PZ_SERVER_NAME=${SERVER_NAME}
PZ_XMX=${XMX}
PZ_IDLE_WARN_MIN=$(get idle_warn_min)
PZ_IDLE_TIMEOUT_MIN=$(get idle_timeout_min)
PZ_SESSION_CAP_HOURS=$(get session_cap_hours)
PZ_DOWN_TIMEOUT_MIN=$(get down_timeout_min)
PZ_BACKUP_BUCKET=$(get backup_bucket)
PZ_ALERT_TOPIC_ARN=$(get alert_topic_arn)
PZ_AUDIT_LOG_GROUP=$(get audit_log_group)
PZ_RCON_HOST=127.0.0.1
PZ_RCON_PORT=27015
PZ_RCON_PASSWORD=${RCON_PASSWORD}
PZ_ADMIN_PASSWORD=${ADMIN_PASSWORD}
PZ_ROOT=/opt/pz
PZ_DATA=/opt/pz/data
AWS_DEFAULT_REGION=${REGION}
ENVEOF

# 0640 root:pzuser -- written by root, readable by the service account and nobody else.
#
# It cannot be 0600 root:root: pzserver.service drops to User=pzuser before ExecStart
# runs, and pz-start-server.sh sources this file. It should not be world-readable
# either: per DESIGN C7 the RCON password in here is equivalent to full control of the
# server. Group-reading by pzuser grants that account nothing it does not already have
# -- the same password is in its own Server/*.ini, and the admin password is on its
# command line.
install -m 0640 -o root -g pzuser "$tmp" "$ENV_FILE"
rm -f "$tmp"
log "wrote $ENV_FILE for stack=$STACK server=$SERVER_NAME xmx=$XMX"
